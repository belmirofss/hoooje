const BADGE_COLORS = [
  "var(--color-pop-sky)",
  "var(--color-pop-pink)",
  "var(--color-pop-lilac)",
  "var(--color-pop-orange)",
  "var(--color-pop-lime)",
  "var(--color-pop-yellow)",
];

export const baseCode = (pair: Pair) => pair.code.split("-")[0];

export const badgeSymbol = (pair: Pair) =>
  SYMBOLS[baseCode(pair)] ?? baseCode(pair);

export const badgeColor = (pair: Pair) => {
  const code = baseCode(pair);
  let hash = 0;
  for (const char of code) hash = (hash * 31 + char.charCodeAt(0)) >>> 0;
  return BADGE_COLORS[hash % BADGE_COLORS.length];
};

export const getPair = (slug: string) =>
  pairs.find((pair) => pair.slug === slug);

export const pairLabel = (pair: Pair) =>
  `${pair.name} → ${QUOTE_NAMES[pair.quote]}`;

export const relatedPairs = (pair: Pair, limit = 4) => {
  const others = pairs.filter((other) => other.slug !== pair.slug);
  const sameName = others.filter((other) => other.name === pair.name);
  const sameCategory = others
    .filter(
      (other) => other.category === pair.category && other.name !== pair.name
    )
    .sort((a, b) => b.priority - a.priority);
  return [...sameName, ...sameCategory].slice(0, limit);
};

// "USD/BRL"; the turismo quote is still against the Real.
export const pairSymbol = (pair: Pair) => `${baseCode(pair)}/${pair.quote}`;

export const pairTitle = (pair: Pair) =>
  `Cotação ${pair.article} ${pair.name} hoje em ${QUOTE_NAMES[pair.quote]} (${pairSymbol(pair)})`;

export const pairDescription = (pair: Pair) =>
  `${pair.name} hoje: cotação ${pair.article} ${pair.name} em ${QUOTE_NAMES[pair.quote]} atualizada a cada minuto, com compra, venda, variação do dia, histórico e conversor ${pairSymbol(pair)}.`;
